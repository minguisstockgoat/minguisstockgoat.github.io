import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {unlock,lock,snapshotFetch} from './snapshot-client.ts';
const envelope=JSON.parse(await readFile(new URL('../options-compass/data/snapshot.json',import.meta.url),'utf8'));
const secret=JSON.parse(await readFile(new URL('../../options-compass-kr/.sites-runtime/pages/access.json',import.meta.url),'utf8'));
Object.defineProperty(globalThis,'location',{value:new URL('https://example.test/options-compass/')});
await assert.rejects(unlock('incorrect-password',envelope));
await assert.rejects(snapshotFetch('/api/dashboard'));
const data=await unlock(secret.password,envelope);
assert.ok(data.dashboard.data.contracts.length>0);
assert.equal(data.global.markets.length,17);
const korea=await(await snapshotFetch('/api/dashboard')).json();
assert.equal(korea.data.krxDate,data.dashboard.data.krxDate);
assert.equal(korea.refreshConfigured,false);
const globe=await(await snapshotFetch('/api/global-options')).json();
assert.deepEqual(globe.markets,data.global.markets);
const selected=await(await snapshotFetch('/api/global-options',{method:'POST',body:JSON.stringify({symbol:'HSI'})})).json();
assert.equal(selected.market.symbol,'HSI');
assert.deepEqual(await(await snapshotFetch('/api/history')).json(),data.history);
assert.equal((await(await snapshotFetch('/api/order-flow?date=19990101')).json()).data,null);
const controller=new AbortController();controller.abort();
await assert.rejects(snapshotFetch('/api/history',{signal:controller.signal}),{name:'AbortError'});
lock();
await assert.rejects(snapshotFetch('/api/dashboard'));
const damaged={...envelope,ciphertext:(envelope.ciphertext[0]==='A'?'B':'A')+envelope.ciphertext.slice(1)};
await assert.rejects(unlock(secret.password,damaged));
console.log('PASS: password, authenticated encryption, exact data, routes, date isolation, abort, and lock.');
